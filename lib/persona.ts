/** The type code for a set of picks, with "?" for any fork not yet chosen. */
export function typeCode(picks: (0 | 1 | null)[]) {
  return FORKS.map((f, k) => (picks[k] === null ? "?" : f.codes[picks[k]!][0])).join("");
}
